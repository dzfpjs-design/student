const supplyCodes = new Set([
  'GOAL_CATALOG_SOURCE_CHANGED', 'GOAL_CATALOG_SOURCE_UNBOUND', 'GOAL_RULE_PLAN_CHANGED',
  'SUPPLY_RESUME_BUDGET_UNKNOWN', 'SUPPLY_RESUME_BUDGET_INSUFFICIENT',
  'SUPPLY_RESUME_PLAN_CHANGED', 'SUPPLY_RESUME_SOURCE_CHANGED', 'SUPPLY_RESUME_AUTHORIZATION_CHANGED',
  'TASK_START_LEGACY_REVIEW_CHANGED', 'TASK_START_LEGACY_REVIEW_VOICE_REQUIRED',
  'TASK_START_LEGACY_REVIEW_VOICE_CHANGED', 'TASK_START_LEGACY_REVIEW_PLAN_CHANGED',
  'TASK_START_LEGACY_REVIEW_BUDGET_UNKNOWN', 'TASK_START_LEGACY_REVIEW_BUDGET_INSUFFICIENT',
  'TASK_START_LEGACY_REVIEW_AUTHORIZATION_CHANGED', 'TASK_START_LEGACY_REVIEW_ACTIVE_TASK',
  'TASK_START_LEGACY_REVIEW_PENDING_QUESTION',
  'ANSWER_ORAL_FOLLOWUP_AUTHORITY_CHANGED', 'ANSWER_ORAL_FOLLOWUP_COMMAND_CHANGED',
  'ANSWER_ORAL_FOLLOWUP_GOAL_CHANGED', 'ANSWER_ORAL_FOLLOWUP_CONSENT_CHANGED',
  'ANSWER_ORAL_FOLLOWUP_PROMPT_CHANGED', 'ANSWER_ORAL_FOLLOWUP_VOICE_CHANGED',
  'ANSWER_ORAL_FOLLOWUP_SOURCE_CHANGED', 'ANSWER_ORAL_FOLLOWUP_CANCELLED',
  'ANSWER_ORAL_FOLLOWUP_FAILED_COMMAND', 'ANSWER_ORAL_FOLLOWUP_COMMAND_REQUIRED',
  'ORAL_DAILY_CHECK_FEEDBACK_REQUIRED',
  'SUPPLY_RESUME_ORAL_SOURCE_CHANGED',
])

export function supplyResumeConflictMessage(error: { status?: number; code?: string | null; message: string }): string | null {
  if (error.status !== 409 || !error.code || !supplyCodes.has(error.code)) return null
  if (error.code === 'ORAL_DAILY_CHECK_FEEDBACK_REQUIRED') {
    return '回答已保存，请先核对本次反馈，再结束复查；不用重新回答。'
  }
  if (error.message.trim() && error.message.length <= 240) return error.message
  if (error.code.startsWith('GOAL_')) return '这项旧任务的依据需要核对。请让家长核对当前规则和资料，再按新路线安排；原学习记录仍保留。'
  return error.code.startsWith('ANSWER_ORAL_FOLLOWUP_')
    ? '这次口语练习暂时不能继续，请告诉我现在想练哪道题，再确认下一步。'
    : '原练习暂时不能继续，已保存进度，请先核对材料和今晚可用时间。'
}
